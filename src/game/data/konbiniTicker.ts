/** Mischt Spezialmeldungen gleichmäßig zwischen allgemeine Meldungen. */
function interleave(common: string[], special: string[]): string[] {
  const out: string[] = [];
  const step = Math.max(1, Math.floor(common.length / special.length));
  let s = 0;
  common.forEach((m, i) => {
    out.push(m);
    if ((i + 1) % step === 0 && s < special.length) out.push(special[s++]);
  });
  while (s < special.length) out.push(special[s++]);
  return out;
}

export type KonbiniTickerPool = "e67" | "e71";

export function getKonbiniTickerMessages(pool: KonbiniTickerPool): string[] {
  return interleave(COMMON, pool === "e71" ? E71 : E67);
}

/** Lesegeschwindigkeit des Bandes in Zeichen pro Sekunde. */
export const TICKER_CHARS_PER_SECOND = 3.5;

export function getKonbiniTickerText(pool: KonbiniTickerPool): string {
  return "+++ " + getKonbiniTickerMessages(pool).join(" +++ ") + " +++ ";
}

/** Dauer eines vollständigen Durchlaufs (ohne Wiederholung) in Sekunden. */
export function getTickerDurationSeconds(text: string): number {
  return Math.round(text.length / TICKER_CHARS_PER_SECOND);
}
